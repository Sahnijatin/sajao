# Plausible listing sizes by category (cm): (min, max) of the largest horizontal side and of height.
PLAUSIBLE = {
    "sofa": ((120, 330), (60, 110)),
    "bed": ((150, 230), (20, 140)),
    "almirah": ((60, 260), (120, 240)),
    "table": ((35, 220), (30, 110)),
    "chair": ((40, 110), (55, 130)),
    "lamp": ((10, 70), (20, 210)),
    "tv_unit": ((80, 300), (30, 220)),
    "shelf": ((40, 250), (60, 240)),
}


def load_listings(work: Path) -> list[dict]:
    out = []
    for f in (work / "listings" / "listings.json", work / "extras" / "listings.json"):
        if f.exists():
            out += json.loads(f.read_text())
    return out


def plausible(x: dict) -> bool:
    if x["category"] not in PLAUSIBLE:
        return True
    d = x["dims_cm"]
    horiz = max([d.get(k) or 0 for k in ("width", "depth", "length", "diameter", "shade_diameter")])
    (hl, hh), (vl, vh) = PLAUSIBLE[x["category"]]
    return hl <= horiz <= hh and vl <= d.get("height", 0) <= vh


def saturation(work: Path, x: dict) -> float:
    """Mean chroma of the product's non-white pixels in its main photo (palette sorting)."""
    import cv2

    root = work / ("listings" if (work / "listings" / x["id"]).exists() else "extras") / x["id"]
    img = cv2.imread(str(root / "0.jpg"))
    if img is None:
        return 0.0
    hsv = cv2.cvtColor(cv2.resize(img, (128, 128)), cv2.COLOR_BGR2HSV).reshape(-1, 3).astype(float)
    fg = hsv[(hsv[:, 2] < 235) | (hsv[:, 1] > 25)]
    return float(fg[:, 1].mean()) if len(fg) else 0.0


def size_m(x: dict) -> tuple[float, float, float]:
    """(width along the front, depth, height) in metres from the listing."""
    d = x["dims_cm"]
    hs = sorted([v for v in (d.get("width"), d.get("depth"), d.get("length")) if v], reverse=True)
    if not hs:
        hs = [d.get("diameter") or d.get("shade_diameter") or 40] * 2
    if len(hs) == 1:
        hs = hs * 2
    return hs[0] / 100, hs[1] / 100, (d.get("height") or 40) / 100


def pick(cands: list[dict], used: set, bold: bool, sat: dict, fits=lambda x: True) -> dict | None:
    pool = [x for x in cands if x["id"] not in used and fits(x)]
    if not pool:
        return None
    pool.sort(key=lambda x: (-sat[x["id"]] if bold else sat[x["id"]], x["id"]))
    x = pool[0]
    used.add(x["id"])
    return x


def by_cat(listings, cat, ready: set, tier_mesh=True):
    return [
        x
        for x in listings
        if x["category"] == cat and plausible(x) and (not tier_mesh or x["id"] in ready)
    ]


def unit(deg):
    return np.array([math.cos(math.radians(deg)), math.sin(math.radians(deg))])


def rot_for_front(front_deg: float) -> float:
    """Design rotation that turns an item's local front (-y) to face `front_deg`."""
    return (front_deg + 90.0) % 360.0


def plan(
    room: str, cfg: dict, listings: list[dict], ready: set, sat: dict, slot: str
) -> list[dict]:
    """Items for one design. slot: best_value (Refresh), best_match, bold."""
    f = unit(cfg["front_deg"])
    right = np.array([f[1], -f[0]])
    side = cfg["side"]
    back = np.array(cfg["back"])
    bold = slot == "bold"
    used: set = set()
    items = []

    def add(iid, x, tier, pos, rot, z=0.0, **kw):
        items.append(
            {
                "id": iid,
                "listing": x["id"],
                "tier": tier,
                "position": [round(float(pos[0]), 3), round(float(pos[1]), 3)],
                "rotation_deg": round(rot % 360, 1),
                "z": round(z, 3),
                **kw,
            }
        )

    rugs = [x for x in listings if x["category"] == "rug"]
    arts = [x for x in listings if x["category"] == "art"]
    plants = [
        x for x in listings if x["category"] == "plant" and (x["dims_cm"].get("height") or 0) >= 80
    ]
    lamps = by_cat(listings, "lamp", ready)
    floor_lamps = [x for x in lamps if x["dims_cm"].get("height", 0) >= 100]
    table_lamps = [x for x in lamps if x["dims_cm"].get("height", 0) < 80]
    tables = by_cat(listings, "table", ready)
    slot_i = {"best_value": 0, "best_match": 1, "bold": 2}[slot]

    if cfg["kind"] == "living":
        anchor_depth = 0.95
        if slot == "best_value":
            sofa_w, sofa_d, sofa_h = cfg["max_len"] - 0.1, anchor_depth, 0.85  # existing sofa stays
        else:
            sofas = by_cat(listings, "sofa", ready)
            s = pick(sofas, used, bold, sat, fits=lambda x: size_m(x)[0] <= cfg["max_len"])
            sofa_w, sofa_d, sofa_h = size_m(s)
            add("sofa", s, "mesh", back + f * (sofa_d / 2 + 0.03), rot_for_front(cfg["front_deg"]))
            coffee = pick(
                tables,
                used,
                bold,
                sat,
                fits=lambda x: size_m(x)[2] <= 0.55 and 0.6 <= size_m(x)[0] <= 1.4,
            )
            if coffee:
                _cw, cd, _ = size_m(coffee)
                add(
                    "coffee_table",
                    coffee,
                    "mesh",
                    back + f * (sofa_d + 0.45 + cd / 2),
                    rot_for_front(cfg["front_deg"]),
                )
            chair = pick(
                by_cat(listings, "chair", ready),
                used,
                bold,
                sat,
                fits=lambda x: size_m(x)[0] >= 0.6,
            )
            if chair:
                _aw, ad, _ = size_m(chair)
                pos = back + f * (sofa_d + 0.45 + 0.35) + side * right * (0.5 + 0.45 + ad / 2 + 0.2)
                face = -side * right
                add(
                    "armchair",
                    chair,
                    "mesh",
                    pos,
                    rot_for_front(math.degrees(math.atan2(face[1], face[0]))),
                )
        rug = rugs[(slot_i * 2) % len(rugs)] if rugs else None
        if rug:
            add("rug", rug, "rug", back + f * (sofa_d + 0.45 + 0.25), cfg["front_deg"] + 90)
        if floor_lamps:
            lamp = pick(floor_lamps, used, bold, sat)
            if lamp:
                add(
                    "floor_lamp",
                    lamp,
                    "mesh",
                    back + f * 0.3 - side * right * (sofa_w / 2 + 0.3),
                    rot_for_front(cfg["front_deg"]),
                )
    else:  # bedroom
        if slot == "best_value":
            bed_w, bed_l = 1.6, 2.0
        else:
            beds = by_cat(listings, "bed", ready)
            b = pick(beds, used, bold, sat, fits=lambda x: size_m(x)[1] <= 1.7)
            bed_l, bed_w, _bed_h = size_m(b)  # long side runs along the front direction
            add("bed", b, "mesh", back + f * (bed_l / 2 + 0.03), rot_for_front(cfg["front_deg"]))
            night = pick(
                tables,
                used,
                bold,
                sat,
                fits=lambda x: size_m(x)[0] <= 0.6 and 0.35 <= size_m(x)[2] <= 0.7,
            )
            if night:
                nw, nd, nh = size_m(night)
                pos = back + f * (nd / 2 + 0.05) + (-side) * right * (bed_w / 2 + 0.05 + nw / 2)
                add("nightstand", night, "mesh", pos, rot_for_front(cfg["front_deg"]))
                tl = pick(table_lamps, used, bold, sat)
                if tl:
                    add("table_lamp", tl, "mesh", pos, rot_for_front(cfg["front_deg"]), z=nh)
        rug = rugs[(slot_i * 2 + 1) % len(rugs)] if rugs else None
        if rug:
            add("rug", rug, "rug", back + f * (bed_l * 0.8), cfg["front_deg"] + 90)
        if slot == "best_value" and floor_lamps:
            lamp = pick(floor_lamps, used, bold, sat)
            if lamp:
                add(
                    "floor_lamp",
                    lamp,
                    "mesh",
                    back + f * 0.3 + side * right * (bed_w / 2 + 0.35),
                    rot_for_front(cfg["front_deg"]),
                )
        sofa_w, sofa_h = bed_w, 1.0
    if arts:
        art = arts[(slot_i * 2) % len(arts)]
        add(
            "wall_art",
            art,
            "art",
            back + f * 0.02,
            rot_for_front(cfg["front_deg"]),
            z=round(sofa_h + 0.3, 2),
        )
    if plants:
        p = plants[slot_i % len(plants)]
        add("plant", p, "billboard", back + f * 0.35 + side * right * (sofa_w / 2 + 0.35), 0.0)
    return items


# ---------- hero camera ----------


def project(k, c2w, pts_world):
    w2c = np.linalg.inv(c2w)
    pc = pts_world @ w2c[:3, :3].T + w2c[:3, 3]
    z = pc[:, 2]
    uv = pc[:, :2] / np.maximum(z[:, None], 1e-6) * [k[0, 0], k[1, 1]] + [k[0, 2], k[1, 2]]
    return uv, z


def to_world(fr, p):
    return np.asarray(p) @ np.asarray(fr["R"]) + np.asarray(fr["origin"])


def item_box_world(fr, it, listing) -> np.ndarray:
    w, d, h = size_m(listing)
    if it["tier"] == "rug":
        h = 0.01
    if it["tier"] == "art":
        d = 0.03
    yaw = math.radians(it["rotation_deg"])
    c, s = math.cos(yaw), math.sin(yaw)
    pts = []
    for sx in (-0.5, 0.5):
        for sy in (-0.5, 0.5):
            for sz in (0, 1):
                lx, ly = sx * w, sy * d
                pts.append(
                    [
                        it["position"][0] + c * lx - s * ly,
                        it["position"][1] + s * lx + c * ly,
                        it["z"] + sz * h,
                    ]
                )
    return to_world(fr, np.array(pts))


def hero_frame(fr, cams: dict, items, lmap) -> tuple[int, dict]:
    """Keyframe that shows every item of every design inside the frame, largest on screen."""
    best = None
    for i, f in enumerate(cams["frames"]):
        k = np.asarray(f["K"])
        c2w = np.asarray(f["c2w"])
        w, h = f["w"], f["h"]
        inside, area, behind, wsum = 0.0, 0.0, 0, 0.0
        for it in items:
            sw, sd, sh = size_m(lmap[it["listing"]])
            wt = sw * max(sd, 0.3) * max(sh, 0.3)  # big items matter most
            wsum += wt
            uv, z = project(k, c2w, item_box_world(fr, it, lmap[it["listing"]]))
            if (z < 0.4).any():
                behind += 1
                continue
            ok = (
                (uv[:, 0] >= -0.02 * w)
                & (uv[:, 0] <= 1.02 * w)
                & (uv[:, 1] >= -0.02 * h)
                & (uv[:, 1] <= 1.02 * h)
            )
            inside += wt * ok.mean()
            x0, y0 = np.clip(uv.min(0), 0, [w, h])
            x1, y1 = np.clip(uv.max(0), 0, [w, h])
            area += (x1 - x0) * (y1 - y0) / (w * h)
        score = inside / wsum - 0.5 * behind / len(items) + 0.15 * min(area, 1.0)
        if best is None or score > best[0]:
            best = (
                score,
                i,
                {
                    "weighted_inside": round(float(inside / wsum), 3),
                    "behind": behind,
                    "screen_area": round(float(area), 3),
                },
            )
    return best[1], best[2]


# ---------- schema Design objects ----------


def product(x: dict) -> dict:
    w, d, h = size_m(x)
    group = (
        "lighting"
        if x["category"] == "lamp"
        else ("decor" if x["category"] in ("rug", "art", "plant") else "furniture")
    )
    price = round((x.get("price_inr") or 0) * 100)
    dim = lambda v: {"value_m": round(v, 3), "source": "estimated", "error_band_m": 0.02}  # noqa: E731
    return {
        "schema_version": "1.0",
        "id": str(uuid.uuid5(uuid.NAMESPACE_URL, x["url"])),
        "source": "eval-only:" + x["source"].lower().replace(" ", "-"),
        "sku": x["id"],
        "title": x["name"],
        "group": group,
        "category": x["category"],
        "dimensions": {"width": dim(w), "depth": dim(d), "height": dim(h)},
        "price": {"currency": "INR", "amount_minor": price},
        "in_stock": True,
        "checked_at": "2026-11-16T00:00:00Z",
        "images": [u for u in x["images"][:3]],
        "image_use_permitted": True,
        "routes": [
            {
                "kind": "buy",
                "retailer": x["source"],
                "url": x["url"],
                "price": {"currency": "INR", "amount_minor": price},
            }
        ],
    }


def design_object(room: str, slot: str, archetype: str, items: list[dict], lmap: dict) -> dict:
    total = sum(round((lmap[i["listing"]].get("price_inr") or 0) * 100) for i in items)
    return {
        "schema_version": "1.0",
        "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"bakeoff/{room}/{slot}")),
        "space_profile_id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"bakeoff/{room}")),
        "brief_id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"bakeoff/{room}/brief")),
        "created_at": "2026-11-16T00:00:00Z",
        "slot": slot,
        "archetype": archetype,
        "items": [
            {
                "id": i["id"],
                "product": product(lmap[i["listing"]]),
                "position": {"x_m": i["position"][0], "y_m": i["position"][1]},
                "rotation_deg": i["rotation_deg"] % 360,
                "placed_by": "user",
            }
            for i in items
        ],
        "materials": {},
        "lighting": {"layers": ["ambient", "accent"]},
        "total_cost": {"currency": "INR", "amount_minor": total},
        "relaxations": [],
        "check_report": {
            "passed": True,
            "checked_at": "2026-11-16T00:00:00Z",
            "budget_ok": True,
            "stock_ok": True,
            "rules": [
                {
                    "rule": "hand_placed_for_render_bakeoff",
                    "kind": "soft",
                    "passed": True,
                    "detail": "Placed by rule for the render bake-off; not run through the solver.",
                }
            ],
        },
        "explanations": [
            "Render bake-off fixture: placed by explicit rules, not by the design engine."
        ],
    }


def main(work: Path) -> None:
    import cv2
    import jsonschema
    from referencing import Registry, Resource

    listings = load_listings(work)
    lmap = {x["id"]: x for x in listings}
    ready = (
        set(json.loads((work / "ready.json").read_text()))
        if (work / "ready.json").exists()
        else set(lmap)
    )
    sat = {x["id"]: saturation(work, x) for x in listings}
    schemas = REPO / "packages" / "schemas" / "schemas" / "v1"
    reg = Registry()
    for f in schemas.glob("*.json"):
        s = json.loads(f.read_text())
        reg = reg.with_resource(s["$id"], Resource.from_contents(s))
        reg = reg.with_resource(f.name, Resource.from_contents(s))
    design_schema = json.loads((schemas / "design.schema.json").read_text())
    validator = jsonschema.Draft202012Validator(
        design_schema, registry=reg, format_checker=jsonschema.FormatChecker()
    )
    OUT.mkdir(parents=True, exist_ok=True)
    (work / "overlays").mkdir(exist_ok=True)
    for room, cfg in ROOMS.items():
        survey = json.loads((work / "survey" / f"{room}.json").read_text())
        fr = survey["frame"]
        cams = json.loads((work / "cameras" / f"{room}.json").read_text())
        designs, objs, all_items = [], [], []
        arche = {
            "best_value": "refresh",
            "best_match": "conversation_set" if cfg["kind"] == "living" else "bed_centred",
            "bold": "statement",
        }
        for slot in ("best_value", "best_match", "bold"):
            items = plan(room, cfg, listings, ready, sat, slot)
            variant = "original" if slot == "best_value" else "zone"
            designs.append(
                {
                    "id": f"{room.split('_')[-1]}_{slot}",
                    "slot": slot,
                    "variant": variant,
                    "items": items,
                }
            )
            obj = design_object(room, slot, arche[slot], items, lmap)
            errs = sorted(validator.iter_errors(obj), key=str)
            if errs:
                raise SystemExit(f"{room} {slot}: {errs[0].message} at {list(errs[0].path)}")
            objs.append(obj)
            all_items += items
        hero, why = hero_frame(fr, cams, all_items, lmap)
        if (
            "hero" in cfg
        ):  # chosen by hand from the top candidates (the best-scoring ones look into a telescope)
            hero, why = cfg["hero"], {"chosen_by_hand": True, "auto_choice": hero, **why}
        zx0, zx1, zy0, zy1 = cfg["zone"]
        clear_ids = [
            b["id"]
            for b in survey["boxes"]
            if zx0 <= b["center"][0] <= zx1
            and zy0 <= b["center"][1] <= zy1
            and not any(k in b["label"] for k in NEVER_CLEAR)
        ]
        # A similar SKU for the planted "wrong product" error: same category, next in colour order.
        similar = {}
        for it in all_items:
            x = lmap[it["listing"]]
            if it["tier"] == "mesh":
                pool = sorted(
                    [y for y in by_cat(listings, x["category"], ready) if y["id"] != x["id"]],
                    key=lambda y: abs(sat[y["id"]] - sat[x["id"]]),
                )
                if pool:
                    similar[x["id"]] = pool[0]["id"]
        plant_extra = [p for p in listings if p["category"] == "plant"]
        f = unit(cfg["front_deg"])
        right = np.array([f[1], -f[0]])
        planted = (
            {
                "listing": plant_extra[-1]["id"],
                "tier": "billboard",
                "position": (np.array(cfg["back"]) + f * 1.6 + right * 0.9 * -cfg["side"])
                .round(3)
                .tolist(),
                "rotation_deg": 0.0,
                "scale": 1.0,
            }
            if plant_extra
            else None
        )
        room_file = {
            "room": room,
            "hero_frame": hero,
            "hero_why": why,
            "clear": {"zone": clear_ids},
            "designs": designs,
            "similar": similar,
            "planted_plant": planted,
            "config": cfg,
        }
        (OUT / f"{room}.json").write_text(json.dumps(room_file, indent=1))
        (OUT / f"{room}.designs.json").write_text(json.dumps(objs, indent=1))
        # Overlay: item boxes projected on the hero keyframe, one colour per design.
        img_p = work / "frames" / room / "images" / f"{hero:04d}.jpg"
        if img_p.exists():
            img = cv2.imread(str(img_p))
            fcam = cams["frames"][hero]
            for di, d in enumerate(designs):
                col = [(0, 255, 255), (0, 200, 0), (255, 0, 255)][di]
                for it in d["items"]:
                    uv, z = project(
                        np.asarray(fcam["K"]),
                        np.asarray(fcam["c2w"]),
                        item_box_world(fr, it, lmap[it["listing"]]),
                    )
                    if (z > 0.2).all():
                        hull = cv2.convexHull(uv.astype(np.float32)).astype(np.int32)
                        cv2.polylines(img, [hull], True, col, 1)
            cv2.imwrite(str(work / "overlays" / f"{room}.jpg"), img)
        print(room, "hero", hero, why, "clear", clear_ids, [len(d["items"]) for d in designs])


if __name__ == "__main__":
    main(Path(sys.argv[1]))
